// 测试清单生成器：按文件名规则统计各层测试文件数量，写进文档里的一段生成区块。
// 放在哪里：<your-repo>/scripts/test-inventory.mjs
//
//   node scripts/test-inventory.mjs --write   # 重写文档里的区块
//   node scripts/test-inventory.mjs --check   # 区块过期时退出码 1（放进 verify 和 CI）
//
// 为什么需要：文档里手写的数字（“2400+ 个测试”“45 个文件”）很快就过时，
// 而 Agent 会把文档当作事实来读。数字必须从文件树里算出来。
//
// 要改的地方：
// 1. DOC_PATH：清单所在的文档（相对仓库根目录）。
// 2. IGNORED_DIRS：不参与统计的目录。
// 3. LAYERS：每一层的名称和匹配规则，按顺序匹配，先命中的层计数，后面的层不再看。
// 4. 在文档里放一对标记（START / END），第一次运行 --write 前手动加上。
// 5. package.json 加两条脚本（verify-scripts.jsonc 的可选脚本里有同样的两行）：
//      "test:inventory": "node scripts/test-inventory.mjs --write",
//      "test:inventory:check": "node scripts/test-inventory.mjs --check"
//    再把 npm run test:inventory:check 串进 verify:full（typecheck 后面），CI 的 test job 里也加一步。
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const DOC_PATH = 'TESTING.md';
export const START = '<!-- test-inventory:start -->';
export const END = '<!-- test-inventory:end -->';

const IGNORED_DIRS = new Set(['node_modules', '.git', 'dist', 'coverage', 'test-results', '.scratch']);

// 每一层：label 显示在表格里，match 接收仓库相对路径（用 / 分隔）
export const LAYERS = [
  { label: 'Quarantined (`src/__tests__/quarantine/`)', match: (f) => /^src\/__tests__\/quarantine\/.*\.test\.tsx?$/.test(f) },
  { label: 'E2E (`e2e/*.spec.ts`, Playwright)', match: (f) => /^e2e\/.*\.spec\.ts$/.test(f) },
  { label: 'Integration (`*.integration.test.ts`)', match: (f) => /\.integration\.test\.tsx?$/.test(f) },
  { label: 'Contract (`*.contract.test.ts`)', match: (f) => /\.contract\.test\.tsx?$/.test(f) },
  { label: 'Unit (`*.test.ts(x)`)', match: (f) => /\.test\.tsx?$/.test(f) },
  { label: 'Node `node:test` scripts (`*.test.mjs` / `*.test.cjs`)', match: (f) => /\.test\.(mjs|cjs)$/.test(f) },
];

function walk(dir, out = []) {
  // 读不到目录就直接抛出错误，不跳过：统计漏掉目录会让数字悄悄变少
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (IGNORED_DIRS.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

export function collectInventory(repoRoot) {
  const counts = LAYERS.map(() => 0);
  const files = walk(repoRoot).map((f) => path.relative(repoRoot, f).split(path.sep).join('/'));
  for (const file of files) {
    const index = LAYERS.findIndex((layer) => layer.match(file));
    if (index !== -1) counts[index] += 1;
  }
  return counts;
}

export function renderBlock(counts) {
  return [
    START,
    '<!-- generated by `npm run test:inventory` — do not edit by hand; CI runs `test:inventory:check` -->',
    '| Layer | Files |',
    '|---|---|',
    ...LAYERS.map((layer, i) => `| ${layer.label} | ${counts[i]} |`),
    END,
  ].join('\n');
}

export function applyBlock(markdown, block) {
  const s = markdown.indexOf(START);
  const e = markdown.indexOf(END);
  if (s === -1 || e === -1 || e < s) {
    throw new Error(`test-inventory: markers not found in ${DOC_PATH} (${START} … ${END})`);
  }
  // 沿用文档自己的换行符：Windows 上 autocrlf 检出的文件是 CRLF，CI 上是 LF
  const eol = markdown.includes('\r\n') ? '\r\n' : '\n';
  return markdown.slice(0, s) + block.replace(/\r?\n/g, eol) + markdown.slice(e + END.length);
}

function main(argv) {
  const rootIdx = argv.indexOf('--root');
  if (rootIdx !== -1 && !argv[rootIdx + 1]) throw new Error('test-inventory: --root requires a path');
  const repoRoot = rootIdx !== -1
    ? path.resolve(argv[rootIdx + 1])
    : path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const docPath = path.join(repoRoot, DOC_PATH);
  const current = readFileSync(docPath, 'utf8');
  const next = applyBlock(current, renderBlock(collectInventory(repoRoot)));
  if (argv.includes('--write')) {
    if (next !== current) writeFileSync(docPath, next);
    console.log(`test-inventory: ${DOC_PATH} block ${next === current ? 'already up to date' : 'written'}`);
    return 0;
  }
  if (next === current) {
    console.log(`test-inventory: ${DOC_PATH} block is up to date`);
    return 0;
  }
  console.error(`test-inventory: ${DOC_PATH} block is STALE. Run \`npm run test:inventory\` and commit the result.`);
  return 1;
}

const invokedDirectly = Boolean(process.argv[1]) && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  process.exit(main(process.argv.slice(2)));
}
